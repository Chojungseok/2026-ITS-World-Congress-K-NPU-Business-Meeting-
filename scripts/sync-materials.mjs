import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {MATERIAL_CATALOG as catalog} from '../assets/js/material-catalog.js';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..'), check=process.argv.includes('--check');
export function validateCatalog(value, {verifyFile} = {}) {
  if(!value || typeof value.version !== 'string' || !Array.isArray(value.companies) || !Array.isArray(value.materials)) throw Error('Invalid material catalog');
  const companies=new Map(), ids=new Set(), presentation=new Set();
  for(const c of value.companies) {
    if(!/^[a-z0-9][a-z0-9_-]{0,63}$/.test(c.companyId) || !['NPU','ITS'].includes(c.companyType) || typeof c.name!=='string' || !c.name.trim() || c.name.length>80 || companies.has(c.companyId))throw Error('Invalid/duplicate company');
    companies.set(c.companyId,c);
  }
  for(const m of value.materials) {
    const c=companies.get(m.companyId);
    if(!/^[A-Z0-9][A-Z0-9_-]{0,79}$/.test(m.materialId) || ids.has(m.materialId) || !c || c.companyType!==m.companyType || !['presentation','brochure'].includes(m.materialType) || typeof m.title!=='string' || !m.title.trim() || m.title.length>160 || typeof m.available!=='boolean' || typeof m.publicApproved!=='boolean')throw Error('Invalid/duplicate material');
    ids.add(m.materialId);
    if(m.materialType==='presentation') {if(presentation.has(m.companyId))throw Error('One presentation per company');presentation.add(m.companyId);}
    if(m.filePath!==null && (typeof m.filePath!=='string' || !/^assets\/(brochures|materials)\/[a-z0-9/_-]+\.pdf$/.test(m.filePath) || m.filePath.includes('..')))throw Error('Invalid PDF path');
    if(m.available && (!m.publicApproved || !m.filePath))throw Error('Available material needs released PDF');
    if(m.filePath)verifyFile?.(m);
  }
}
validateCatalog(catalog,{verifyFile:m=>{
  const full=path.resolve(root,m.filePath),bytes=fs.readFileSync(full);
  if(!bytes.subarray(0,5).equals(Buffer.from('%PDF-')))throw Error('Not an existing PDF: '+m.filePath);
}});
const source=fs.readFileSync(path.join(root,'assets/js/material-stats.js'),'utf8').replace('export function aggregateMaterialViews','function aggregateMaterialViews');
const outputs={
  'apps-script/MaterialCatalog.gs':'// GENERATED by npm run sync-materials from material-catalog.js. Never edit.\nvar MATERIAL_CATALOG_SEED = '+JSON.stringify(catalog,null,2)+';\n',
  'apps-script/MaterialStats.gs':'// GENERATED by npm run sync-materials from material-stats.js. Never edit.\n'+source
};
for(const [name,content] of Object.entries(outputs)){
 const target=path.join(root,name);
 if(check){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8').replace(/\r\n/g,'\n')!==content)throw Error('Run npm run sync-materials: '+name);}
 else fs.writeFileSync(target,content);
}
console.log('Material registry checked: '+catalog.materials.length+' entries; no placeholder PDFs.');
